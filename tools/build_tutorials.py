#!/usr/bin/env python3
"""Builds the three tutorials, in English and in Portuguese, from tools/tutorials_content.py and
tools/tutorials_content_pt.py (the same text as the sheets of the Figma page 'Tutorials'):
    docs/en/tutorials-{designers,developers,ai}.md and docs/pt-br/tutorials-{designers,developers,ai}.md

Usage: python3 tools/build_tutorials.py            # write
       python3 tools/build_tutorials.py --check    # fail if out of date
No dependencies (Python 3.8+).
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import tutorials_content as EN
from aipim_tools import ROOT, sync
import tutorials_content_pt as PT

HEADER = ('<!-- Aipim design system · https://github.com/talis-galhardi/aipim · MIT License · Copyright (c) 2026 Talis Galhardi · '
          'Generated by tools/build_tutorials.py from {src}: do not edit by hand. -->')
LABELS_EN = {
    'tutorial_of': 'Tutorial {n} of 3', 'choose': 'Choose your tutorial', 'table_head': '| Tutorial | For | Where | File |',
    'here': ' (you are here)', 'fit': 'Where this fits', 'stage_head': '| Stage | Name | Where it is covered |',
    'this_tutorial': 'This tutorial', 'six_steps': 'The six steps', 'need': 'You need', 'have': 'You will have', 'step': 'Step',
    'done': 'Done when', 'final': 'Final check', 'final_intro': 'Tick every line before you move on.', 'keep': 'Keep these close',
    'names': 'Same names everywhere', 'names_head': '| In Figma | In code |', 'ask': 'Need something new? Ask in this order',
}
# (content, labels, docs folder, source file)
LANGS = [(EN, LABELS_EN, 'docs/en', 'tools/tutorials_content.py'), (PT, PT.LABELS, 'docs/pt-br', 'tools/tutorials_content_pt.py')]


def build(t, W, L, folder, src):
    n = t['n']
    o = [HEADER.format(src=src), f'# {W.HEADINGS[n]}', '', f'*{L["tutorial_of"].format(n=n)} · {t["audience"]}*', '', t['lead'], '',
         f'## {L["choose"]}', '', W.CHOOSE_INTRO, '', L['table_head'], '|---|---|---|---|']
    for pn, title, aud, where, file in W.PATHS:
        mark = L['here'] if pn == n else ''
        o.append(f'| {pn}. {title}{mark} | {aud} | {where} | `{folder}/{file}.md` |')
    o += ['', f'## {L["fit"]}', '', W.FIT_INTRO, '', W.FIT[n]['lead'], '', L['stage_head'], '|---|---|---|']
    for sn, name, where in W.STAGES:
        o.append(f'| {sn} | {name} | ' + (f'**{L["this_tutorial"]}: {W.FIT[n]["steps"][sn].lower()}**' if sn in W.FIT[n]['steps'] else where) + ' |')
    o.append('')
    if n == 1:
        o += [W.STAKEHOLDERS, '']
    o += [f'## {L["six_steps"]}: {t["title"]}', '', f'**{L["need"]}**', ''] + [f'- {x}' for x in t['need']] + ['', f'**{L["have"]}**', ''] + [f'- {x}' for x in t['have']] + ['']
    for i, (title, body, code, done) in enumerate(t['steps'], 1):
        o += [f'### {L["step"]} {i}: {title}', '', body, '']
        if code:
            label, lang, text = code
            o += [f'*{label}*', '', f'```{lang}', text, '```', '']
        o += [f'**{L["done"]}** {done}', '']
    o += [f'### {L["final"]}', '', L['final_intro'], ''] + [f'- [ ] {x}' for x in t['check']] + ['']
    for title, lead, cards in W.REFERENCE.get(n, []):
        o += [f'## {title}', '', lead, '']
        for over, ctitle, items in cards:
            o += [f'### {ctitle}', '', f'*{over}*', ''] + [f'- {x}' for x in items] + ['']
    if n in W.KEEP_IN:
        o += [f'## {L["keep"]}', '', W.KEEP_INTRO, '', f'### {L["names"]}', '', L['names_head'], '|---|---|']
        o += [f'| {a} | {c} |' for a, c in W.NAMES]
        o += ['', f'### {L["ask"]}', ''] + [f'{i}. {x}' for i, x in enumerate(W.ASK, 1)] + ['', W.STUCK]
    return '\n'.join(o).rstrip() + '\n'


def outputs():
    out = {}
    for W, L, folder, src in LANGS:
        for n, _, _, _, file in W.PATHS:
            out[f'{folder}/{file}.md'] = build(next(t for t in W.TUTORIALS if t['n'] == n), W, L, folder, src)
    return out


if __name__ == '__main__':
    sys.exit(sync(outputs(), 'python3 tools/build_tutorials.py', 'the six tutorials (English and Portuguese) are'))
