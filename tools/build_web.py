#!/usr/bin/env python3
"""Aipim web components builder.

The component styles live in components/web/*.css, one file per component, so you can copy only what you need.
This script joins them into one file for people who want everything:

    python3 tools/build_web.py          # writes components/web/aipim-components.css
    python3 tools/build_web.py --check  # exits 1 if the joined file is out of date

It also writes the parts of other files that come from a source: the icons inline in the gallery and the theme builder
(from icons/sprite.svg), and the color data of the theme builder's engine (from tools/build_tokens.py).

Order matters: aipim-base.css first, then the components (checkbox.css defines .aipim-choice-group, which radio.css reuses).
"""
import json, os, re, sys

from aipim_tools import ROOT, read, replace_between, specs, sync
import build_tokens as bt

WEB = os.path.join(ROOT, 'components', 'web')
BUNDLE = 'aipim-components.css'
FILES = ['aipim-base.css', 'button.css', 'icon-button.css', 'link.css', 'text-field.css', 'select.css', 'combobox.css',
         'datepicker.css', 'list-item.css', 'accordion.css', 'checkbox.css', 'radio.css', 'switch.css', 'alert.css',
         'toast.css', 'empty-state.css', 'badge.css', 'avatar.css', 'tag.css', 'card.css', 'top-bar.css', 'tab-bar.css',
         'tabs.css', 'modal.css']
HEADER = ('/* Aipim design system · https://github.com/talis-galhardi/aipim · MIT License · Copyright (c) 2026 Talis Galhardi\n'
          '   Generated by tools/build_web.py from the files in components/web/: do not edit by hand.\n'
          '   Load tokens/build/css/aipim.css first. */\n')


def build():
    parts = [HEADER]
    for name in FILES:
        lines = read(f'components/web/{name}').split('\n')
        if lines and lines[0].startswith('/* Aipim design system'):
            lines = lines[1:]  # drop the per-file credit line; the joined file has one at the top
        parts.append(f'\n/* ---- {name} ---- */\n' + '\n'.join(lines).strip('\n') + '\n')
    return ''.join(parts)


# Pages that carry their icons inline (a page opened from the disk cannot <use> an external sprite in every browser).
# A page names the scripts that write icons of their own, and the icons those scripts pick while they run, which no
# reading of the source settles (`icon(ok ? 'check' : 'error')` names two of them). The block holds those and the ones
# the markup points at, and nothing else: an icon already in the page is no reason to keep it, so a page that stops
# using one loses it on the next build.
ICON_PAGES = {
    'components/web/examples/index.html': {'scripts': ['components/web/aipim.js'], 'runtime': []},
    'theme-builder/index.html': {
        'scripts': ['theme-builder/app.js'],
        'runtime': ['arrow-right', 'check', 'chevron-down', 'error', 'success', 'warning'],
    },
}
ICONS_START = '<!-- icons:start: only the icons this page uses, written by tools/build_web.py from icons/sprite.svg (Hugeicons Free, MIT) -->'


def inline_icons(page, scripts, runtime, fresh=None):
    """The icons of a page, copied from the sprite: the ones its markup points at and the ones its scripts pick.

    `fresh` holds the files this run already rewrote, so a script whose icons changed is read as it will be on disk
    and not as it was.
    """
    sprite = {name: symbol for symbol, name
              in re.findall(r'(<symbol id="aipim-([a-z0-9-]+)".*?</symbol>)', read('icons/sprite.svg'), re.S)}
    text = read(page)
    scripts_text = ''.join((fresh or {}).get(s) or read(s) for s in scripts)
    used = set(re.findall(r'#aipim-([a-z0-9-]+)', text + scripts_text)) | set(runtime)
    # Every name a script hands to icon() has to be covered, a name inside a ternary too. Without this, an icon added
    # to a script and to nothing else would quietly never reach the page, and only show up as a hole in the layout.
    named = {n for call in re.findall(r'\bicon\(([^()]*)\)', scripts_text) for n in re.findall(r"'([a-z0-9-]+)'", call)}
    undeclared = sorted(named - used)
    if undeclared:
        raise SystemExit(f"{page}: add to its 'runtime' icons in tools/build_web.py: {', '.join(undeclared)}")
    unknown = sorted(used - set(sprite))
    if unknown:
        raise SystemExit(f"{page} uses icons that are not in icons/sprite.svg: {', '.join(unknown)}")
    block = '\n'.join(sprite[n] for n in sprite if n in used)
    return replace_between(text, ICONS_START, '<!-- icons:end -->', block)


# The masks and the checks of the Brazilian field have one source, components/web/aipim-br.js, which is a module so a
# server, a framework or a test can import the plain functions. The browser file is a script, loaded with <script>,
# and a script cannot carry `export`, so the code is copied into it between markers with the keyword dropped. The two
# can never disagree: --check fails when the copy is behind.
BR_START = '  // br:start: written by tools/build_web.py from components/web/aipim-br.js: do not edit by hand'


def br_block():
    # The module's own header comments stay out: the browser file has its own at the top.
    body = re.sub(r'\A(?:/\*(?:[^*]|\*(?!/))*\*/\s*)+', '', read('components/web/aipim-br.js')).strip('\n')
    body = body.replace('export function ', 'function ')
    inner = '\n'.join('  ' + line if line.strip() else line for line in body.split('\n'))
    return replace_between(read('components/web/aipim.js'), BR_START, '  // br:end', inner)


# The color data of the theme builder's engine comes from tools/build_tokens.py, so the two never drift apart.
DATA_START = '  // data:start: written by tools/build_web.py from tools/build_tokens.py (seeds, scales, roles, checks): do not edit by hand'


def js(value):
    return json.dumps(value, ensure_ascii=False, separators=(', ', ': '))


def engine_data():
    seeds = {n: {'h': h, 'c': c} for n, (h, c, _) in bt.SEEDS.items()}
    seeds['neutral'] = {'h': bt.NEUTRAL_SEED[0], 'c': bt.NEUTRAL_SEED[1]}
    lines = [f'  const DEFAULT_SEEDS = {js(seeds)};']
    for name in ('STEPS', 'LIGHT', 'CHROMA', 'LIGHT_NUDGE', 'CHROMA_NUDGE', 'NL', 'NC'):
        lines.append(f'  const {name} = {js(getattr(bt, name))};')
    lines.append('  const SEMANTIC = {')
    for mode, roles in bt.SEMANTIC.items():
        lines.append(f'    {mode}: {{')
        lines += [f'      {js(k)}: {js(list(v))},' for k, v in roles.items()]
        lines.append('    },')
    lines.append('  };')
    lines.append('  // [foreground, background, minimum ratio, label]')
    lines.append('  const CHECKS = [')
    lines += [f'    {js(list(c))},' for c in bt.CHECKS]
    lines.append('  ];')
    lines.append(f'  const CVD = {{')
    lines += [f'    {k}: {js(m)},' for k, m in bt.CVD.items()]
    lines.append('  };')
    lines.append(f'  const CVD_PAIRS = {js([list(p) for p in bt.CVD_PAIRS])};')
    lines.append(f'  const CVD_MIN = {bt.CVD_MIN}, LINK_VS_TEXT_MIN = {bt.LINK_VS_TEXT_MIN};')
    return replace_between(read('theme-builder/theme.js'), DATA_START, '  // data:end', '\n'.join(lines))


def main():
    # The order is the cascade order, so it stays written here; these two checks only make sure no component is left
    # out. A component styled by another one's file (the Brazilian field uses text-field.css) names that file in its "css:".
    missing = sorted({os.path.basename(meta['css']) for _, meta, _ in specs().values()} - set(FILES))
    if missing:
        print(f"Add to FILES in tools/build_web.py: {', '.join(missing)}")
        return 1
    # And the folder, in both directions: a file nobody named here would be left out of the bundle without a word, and
    # a name whose file is gone would only fail later, while the bundle is read.
    on_disk = {name for name in os.listdir(WEB) if name.endswith('.css')} - {BUNDLE}
    if on_disk != set(FILES):
        for what, names in (('Add to', on_disk - set(FILES)), ('Remove from', set(FILES) - on_disk)):
            if names:
                print(f"{what} FILES in tools/build_web.py: {', '.join(sorted(names))}")
        return 1
    outputs = {f'components/web/{BUNDLE}': build(), 'components/web/aipim.js': br_block()}
    outputs.update({page: inline_icons(page, fresh=outputs, **how) for page, how in ICON_PAGES.items()})
    outputs['theme-builder/theme.js'] = engine_data()
    return sync(outputs, 'python3 tools/build_web.py', 'aipim-components.css, the Brazilian field inside aipim.js, the icons of the gallery and the theme builder, and the color data of the theme builder are')


if __name__ == '__main__':
    sys.exit(main())
