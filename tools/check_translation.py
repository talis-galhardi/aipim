#!/usr/bin/env python3
"""Keeps the Portuguese docs in step with the English ones.

The English docs (docs/en, stories/en) are the source; the Portuguese ones (docs/pt-br, stories/pt-br) are their
translation, and each one ends with a stamp of the English text it was translated from:

    <!-- Translated from docs/en/components/button.md, sha256 1a2b3c4d5e6f -->

(in an .mdx file the same line is an MDX comment: {/* Translated from ..., sha256 ... */}).

This script checks that every English file has its Portuguese file, that the stamp matches the English file as it is
now (so a change in English that was not carried over is caught), and that the two have the same shape: the same
frontmatter keys and code values, the same number of sections, tables, table rows and code blocks.

    python3 tools/check_translation.py                 # check
    python3 tools/check_translation.py --stamp FILE    # after translating FILE (the Portuguese one), write its stamp

The generated docs (color, typography, space-shape-motion and the tutorials) are not checked here: their generators
write both languages from one place (tools/build_tokens.py, tools/build_tutorials.py).
Exit code 0 when everything is in step.
"""
import glob
import hashlib
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAIRS = [('docs/en', 'docs/pt-br', '**/*.md'), ('stories/en', 'stories/pt-br', '*.mdx')]
GENERATED = re.compile(r'^<!-- .*Generated by tools/', re.M)
STAMP = re.compile(r'\n*(?:<!--|\{/\*) Translated from (\S+), sha256 ([0-9a-f]{12}) (?:-->|\*/\})\n*$')
# Frontmatter keys whose values are code, not text: they must be the same in both languages.
SAME_KEYS = ('name', 'status', 'group', 'html', 'class', 'css', 'related')


def read(rel):
    with open(os.path.join(ROOT, rel), encoding='utf-8') as f:
        return f.read()


def digest(text):
    # Hex colors are left out: tools/build_specs.py writes them in both languages, so a new palette needs no translation.
    return hashlib.sha256(re.sub(r'#[0-9A-Fa-f]{6}', '#', text).encode('utf-8')).hexdigest()[:12]


def frontmatter(text):
    m = re.match(r'---\n([\s\S]*?)\n---\n', text)
    return dict(re.findall(r'^(\w+):\s*(.*)$', m.group(1), re.M)) if m else {}


def shape(text):
    body = re.sub(r'^(```|~~~)[\s\S]*?^\1', '```', text, flags=re.M)
    tables, rows, inside = 0, 0, False
    for line in body.split('\n'):
        is_row = line.strip().startswith('|')
        if is_row and not inside:
            tables += 1
        rows += is_row
        inside = is_row
    return {
        'sections (##)': len(re.findall(r'^## ', body, re.M)),
        'subsections (###)': len(re.findall(r'^### ', body, re.M)),
        'tables': tables,
        'table rows': rows,
        'code blocks': len(re.findall(r'^(```|~~~)', text, re.M)) // 2,
    }


def pairs():
    for src, dst, pattern in PAIRS:
        for path in sorted(glob.glob(os.path.join(ROOT, src, pattern), recursive=True)):
            en = os.path.relpath(path, ROOT)
            if GENERATED.search(read(en)):
                continue
            yield en, dst + en[len(src):]


def stamp(pt):
    en = next((e for e, p in pairs() if p == pt), None)
    if not en:
        sys.exit(f'{pt} has no English source in {", ".join(s for s, _, _ in PAIRS)}')
    text = STAMP.sub('', read(pt)).rstrip('\n')
    with open(os.path.join(ROOT, pt), 'w', encoding='utf-8') as f:
        line = f'Translated from {en}, sha256 {digest(read(en))}'
        f.write(f'{text}\n\n' + (f'{{/* {line} */}}' if pt.endswith('.mdx') else f'<!-- {line} -->') + '\n')
    print(f'Stamped {pt} from {en}')


def main():
    if '--stamp' in sys.argv:
        for pt in sys.argv[sys.argv.index('--stamp') + 1:]:
            stamp(os.path.relpath(os.path.abspath(pt), ROOT))
        return
    problems = []
    known = set()
    for en, pt in pairs():
        known.add(pt)
        if not os.path.exists(os.path.join(ROOT, pt)):
            problems.append(f'{pt}: missing (translate {en})')
            continue
        text_en, text_pt = read(en), read(pt)
        m = STAMP.search(text_pt)
        if not m:
            problems.append(f'{pt}: no stamp at the end (run: python3 tools/check_translation.py --stamp {pt})')
        elif m.group(1) != en or m.group(2) != digest(text_en):
            problems.append(f'{pt}: {en} changed after the translation. Carry the change over, then stamp it again')
        fe, fp = frontmatter(text_en), frontmatter(STAMP.sub('', text_pt))
        if set(fe) != set(fp):
            problems.append(f'{pt}: frontmatter keys differ from {en}')
        for k in SAME_KEYS:
            if k in fe and fe.get(k) != fp.get(k):
                problems.append(f'{pt}: frontmatter "{k}" differs from {en} (it is code, keep it the same)')
        se, sp = shape(text_en), shape(STAMP.sub('', text_pt))
        for k in se:
            if se[k] != sp[k]:
                problems.append(f'{pt}: {k} {sp[k]}, in English {se[k]}')
    for _, dst, pattern in PAIRS:
        for path in glob.glob(os.path.join(ROOT, dst, pattern), recursive=True):
            rel = os.path.relpath(path, ROOT)
            if rel not in known and not GENERATED.search(read(rel)):
                problems.append(f'{rel}: no English file with the same name')
    for p in problems:
        print('  ' + p)
    n = len(known)
    print(f'{n} translated files, {len(problems)} problem(s).' if problems else f'OK: {n} translated files in step with English.')
    sys.exit(1 if problems else 0)


if __name__ == '__main__':
    main()
