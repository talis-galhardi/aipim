def to_oklab(hexc):
    r, g, b = [lin(c) for c in from_hex(hexc)]
    l = (0.4122214708*r+0.5363325363*g+0.0514459929*b)**(1/3); m = (0.2119034982*r+0.6806995451*g+0.1073969566*b)**(1/3); s = (0.0883024619*r+0.2817188376*g+0.6299787005*b)**(1/3)
    return (0.2104542553*l+0.7936177850*m-0.0040720468*s, 1.9779984951*l-2.4285922050*m+0.4505937099*s, 0.0259040371*l+0.7827717662*m-0.8086757660*s)
def sim(hexc, mat):
    c = [lin(x) for x in from_hex(hexc)]
    return to_hex([max(0, min(1, sum(mat[i][j]*c[j] for j in range(3)))) for i in range(3)])
def de(a, b): return 100*math.dist(to_oklab(a), to_oklab(b))
