def run_checks():
    res, bad = [], []
    for mode in ('light', 'dark'):
        for fg, bg, mn, why in CHECKS:
            r = contrast(SEMV[mode][fg], SEMV[mode][bg]); res.append((mode, fg, bg, mn, why, r, r >= mn))
    fails = [x for x in res if not x[6]]
    cvd = []
    for mode in ('light', 'dark'):
        for a, b in CVD_PAIRS:
            row = {'mode': mode, 'pair': f'{a} × {b}', 'normal': de(SEMV[mode][a], SEMV[mode][b])}
            for k, mat in CVD.items(): row[k] = de(sim(SEMV[mode][a], mat), sim(SEMV[mode][b], mat))
            cvd.append(row)
    cvd_bad = [r for r in cvd for k in ('normal', 'protanopia', 'deuteranopia', 'tritanopia') if r[k] < 8]
    return res, fails, cvd, cvd_bad

