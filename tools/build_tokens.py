def kebab(k): return k.replace('.', '-')
def camel(k):
    p = k.replace('-', '.').split('.'); return p[0] + ''.join(x.capitalize() for x in p[1:])
def pas(k):
    r = ''.join(x.capitalize() for x in k.replace('-', '.').split('.'))
    return ('X' + r) if r[:1].isdigit() else r  # identifiers cannot start with a digit (e.g. radius 2xl -> X2xl)
def srgb_obj(hexc, alpha=None):
    o = {'colorSpace': 'srgb', 'components': [round(c, 4) for c in from_hex(hexc)], 'hex': hexc}
    if alpha is not None: o['alpha'] = alpha
    return o
def dim(v, unit='px'): return {'value': v, 'unit': unit}

