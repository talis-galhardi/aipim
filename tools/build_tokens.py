def oklch_to_lin(L, C, h):
    a = C * math.cos(math.radians(h)); b = C * math.sin(math.radians(h))
    l_ = L + 0.3963377774*a + 0.2158037573*b
    m_ = L - 0.1055613458*a - 0.0638541728*b
    s_ = L - 0.0894841775*a - 1.2914855480*b
    l, m, s = l_**3, m_**3, s_**3
    return (4.0767416621*l - 3.3077115913*m + 0.2309699292*s,
            -1.2684380046*l + 2.6097574011*m - 0.3413193965*s,
            -0.0041960863*l - 0.7034186147*m + 1.7076147010*s)

def in_gamut(rgb): return all(-1e-4 <= v <= 1 + 1e-4 for v in rgb)
def enc(v):
    v = min(1, max(0, v)); return 12.92*v if v <= 0.0031308 else 1.055*v**(1/2.4) - 0.055
def to_hex(lin): return '#%02x%02x%02x' % tuple(round(enc(v)*255) for v in lin)
def from_hex(h):
    h = h.lstrip('#'); return [int(h[i:i+2], 16)/255 for i in (0, 2, 4)]
def lin(c): return c/12.92 if c <= 0.04045 else ((c+0.055)/1.055)**2.4
def lum(hexc):
    r, g, b = [lin(c) for c in from_hex(hexc)]; return 0.2126*r + 0.7152*g + 0.0722*b
def contrast(a, b):
    la, lb = lum(a), lum(b); hi, lo = max(la, lb), min(la, lb); return (hi+0.05)/(lo+0.05)
def make(L, C, h):
    c = C
    while c > 0 and not in_gamut(oklch_to_lin(L, c, h)): c -= 0.002
    return to_hex(oklch_to_lin(L, max(c, 0), h))

