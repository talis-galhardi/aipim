def write(path, text):
    full = os.path.join(ROOT, path); os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, 'w') as f: f.write(text if isinstance(text, str) else json.dumps(text, indent=2, ensure_ascii=False) + '\n')

def main():
    check_only = '--check' in sys.argv
    res, fails, cvd, cvd_bad = run_checks()
    print(f'Contrast: {len(res)} checks, {len(fails)} fail')
    for m, fg, bg, mn, why, r, ok in fails: print(f'  FALHA [{m}] {fg} on {bg}: {r:.2f} (min {mn}) — {why}')
    print('Color blindness (ΔE >= 8 = distinguishable):')
    for r in cvd: print(f"  [{r['mode']}] {r['pair']:40s} normal {r['normal']:5.1f} prot {r['protanopia']:5.1f} deut {r['deuteranopia']:5.1f} trit {r['tritanopia']:5.1f}")
    if fails or cvd_bad:
        print('REJECTED: adjust the seeds or the semantic steps.'); sys.exit(1)
    if check_only: print('OK (nothing written).'); return
    write('tokens/tokens.json', build_dtcg())
    write('tokens/build/css/aipim.css', build_css())
    write('tokens/build/compose/AipimTokens.kt', build_compose())
    write('tokens/build/swift/AipimTokens.swift', build_swift())
    write('tokens/build/figma.json', build_figma())
    langs = ('en', 'pt-br') if '--pt' in sys.argv else ('en',)  # English only by default; --pt also builds the Portuguese version
    for lang in langs:
        write(f'docs/{lang}/color.md', build_color_md(res, cvd, lang))
        write(f'docs/{lang}/typography.md', build_type_md(lang))
    print('OK: tokens/tokens.json, tokens/build/{css,compose,swift,figma}, docs/' + '+'.join(langs) + '/{color,typography}.md')

if __name__ == '__main__': main()
